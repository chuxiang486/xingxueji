import { createHash } from 'node:crypto'
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { basename, extname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = fileURLToPath(new URL('../', import.meta.url))
const manifest = { gallery: {}, wallpapers: {} }
let sourceBytes = 0
let previewBytes = 0

for (const [group, directory, sizes] of [
  ['gallery', 'images', [360, 720]],
  ['wallpapers', 'wallpapers', [480, 960, 1680]],
]) {
  const output = join(root, 'public', 'thumbnails', group)
  await mkdir(output, { recursive: true })
  const files = (await readdir(join(root, 'public', directory)))
    .filter(file => group === 'gallery' ? file.endsWith('.webp') : file.endsWith('.png'))
    .sort()

  for (const file of files) {
    const input = await readFile(join(root, 'public', directory, file))
    const metadata = await sharp(input).metadata()
    const hash = createHash('sha256').update(input).digest('hex').slice(0, 10)
    const variants = []
    const widths = [...new Set(sizes.map(width => Math.min(width, metadata.width)))].sort((a, b) => a - b)
    for (const width of widths) {
      const name = `${basename(file, extname(file))}-${width}-${hash}.webp`
      const info = await sharp(input).rotate().resize({ width, withoutEnlargement: true })
        .webp({ quality: group === 'gallery' ? 78 : 86 }).toFile(join(output, name))
      variants.push({ src: `./thumbnails/${group}/${name}`, width: info.width, bytes: info.size })
    }
    const preview = variants.at(-1)
    manifest[group][file] = {
      width: metadata.width,
      height: metadata.height,
      thumbnail: variants[0].src,
      preview: preview.src,
      srcSet: variants.map(item => `${item.src} ${item.width}w`).join(', '),
    }
    sourceBytes += input.length
    previewBytes += preview.bytes
  }
}

await writeFile(join(root, 'src/data/imageVariants.js'),
  `// Generated by npm run images:build. Keep original images for downloads and lightboxes.\nexport const imageVariants = ${JSON.stringify(manifest, null, 2)}\n`)
console.log(`Created variants for ${Object.keys(manifest.gallery).length} gallery images and ${Object.keys(manifest.wallpapers).length} wallpapers.`)
console.log(`Largest previews: ${(previewBytes / 1024).toFixed(0)} KiB; source images: ${(sourceBytes / 1024).toFixed(0)} KiB.`)
